#!/usr/bin/env bash
# Clean-room, published v0.1.2 CLI -> current-checkout upgrade regression.
# Requires internet access to crates.io. Never runs against a user database.
set -euo pipefail

repo="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

old_root="$work/published-cli"
new_cli="$repo/target/debug/fexu"
mkdir -p "$old_root"
if [[ ! -x "$new_cli" ]]; then
  echo "Build the current CLI first: cargo build -p fexu-cli --bin fexu" >&2
  exit 1
fi

# Install from the public registry, not from the local workspace or Git tag.
cargo install --locked --version 0.1.2 --root "$old_root" fexu-cli
old_cli="$old_root/bin/fexu"
"$old_cli" --version | grep -F '0.1.2'
cd "$work"
"$old_cli" new project V012Consumer --template api
cd V012Consumer
project="$PWD"
db="$project/consumer.sqlite3"
export DATABASE_URL="sqlite://$db?mode=rwc"
export CARGO_TARGET_DIR="$work/app-target"
export CARGO_BUILD_JOBS="${CARGO_BUILD_JOBS:-2}"

# The application and its migration are generated by the *published* CLI.
"$old_cli" new app catalog
"$old_cli" generate model Product --app catalog
"$old_cli" migrate make initial --app catalog
"$old_cli" migrate up

# Keep actual populated business data when switching the dependency.
python3 - "$db" <<'PY'
import sqlite3
import sys
import uuid

connection = sqlite3.connect(sys.argv[1])
try:
    product = connection.execute(
        "SELECT name FROM sqlite_master WHERE type='table' AND name='products'"
    ).fetchone()
    assert product, "published v0.1.2 CLI did not migrate products"
    connection.execute(
        'INSERT INTO "products" ("id", "name") VALUES (?, ?)',
        (str(uuid.UUID(int=2026)), "published-v012-row"),
    )
    connection.commit()
    assert connection.execute('SELECT COUNT(*) FROM "products"').fetchone()[0] == 1
    assert connection.execute("PRAGMA quick_check").fetchone()[0] == "ok"
finally:
    connection.close()
PY

# The generated project must initially resolve the *published* Fexu library.
# Rewrite only its own dependency to the current checkout; don't edit a real
# application, patch crates.io, or install/publish any release candidate.
python3 - "$project/Cargo.toml" "$repo/crates/fexu" <<'PY'
from pathlib import Path
import sys

manifest = Path(sys.argv[1])
current = manifest.read_text()
old = 'fexu = "=0.1.2"'
assert current.count(old) == 1, "published generator changed dependency contract"
path = Path(sys.argv[2]).as_posix()
manifest.write_text(current.replace(old, f'fexu = {{ path = "{path}" }}'))
PY

# The published 0.1.2 generator emitted a call that assumed a String.
# Current Fexu returns Result<String, MigrationError>; migrate the generated
# source explicitly (fail if the upstream historical source ever changes).
python3 - "$project/src/project/mod.rs" <<'PY'
from pathlib import Path
import sys

source = Path(sys.argv[1])
original = source.read_text()
old = '    let db = fexu::db::connect(&settings.resolved_database_url()).await?;'
new = (
    '    let database_url = settings.resolved_database_url()?;\n'
    '    let db = fexu::db::connect(&database_url).await?;'
)
assert original.count(old) == 1, "published 0.1.2 source no longer matches its pinned API"
source.write_text(original.replace(old, new))
PY

# Check the migrated old project against the current checkout. This is a
# documented source edit, NOT an automatic fexu upgrade rewriting source.
cargo check
"$new_cli" upgrade --check
"$new_cli" migrate plan

# Current CLI must extend the old migration chain without rewriting the old
# history or removing the previously inserted business record.
"$new_cli" generate model Customer --app catalog
"$new_cli" migrate make add_customer --app catalog
"$new_cli" migrate up
"$new_cli" migrate plan

python3 - "$db" "$project/apps/catalog/migrations" <<'PY'
from pathlib import Path
import sqlite3
import sys

db, migrations = sys.argv[1:]
connection = sqlite3.connect(db)
try:
    row = connection.execute(
        'SELECT "name" FROM "products" WHERE "name" = ?',
        ("published-v012-row",),
    ).fetchone()
    assert row == ("published-v012-row",), f"historic product row lost: {row}"
    assert connection.execute("PRAGMA quick_check").fetchone()[0] == "ok"
    tables = {row[0] for row in connection.execute(
        "SELECT name FROM sqlite_master WHERE type = 'table'"
    )}
    assert "customers" in tables, f"new version did not migrate customers: {tables}"
    history = connection.execute(
        'SELECT COUNT(*) FROM "_fexu_migrations" WHERE id LIKE ?',
        ("catalog:%",),
    ).fetchone()[0]
    assert history == 2, f"expected two applied catalog migrations, got {history}"
    files = sorted(Path(migrations).glob("*.json"))
    assert len(files) == 2, f"expected two app migration files, got {files}"
finally:
    connection.close()
PY

echo "PASS: published fexu-cli 0.1.2 project upgraded with current Fexu, migrations and data intact"
